#!/usr/bin/env python3
"""Generate the 3x3 torus mini-tutorial page.

The ambient group is the discrete torus A = (Z/3)^2 acting on itself by
translation.  Its six subgroups are computed here, together with the three
independent ways of naming each one used across this project:

  1. as a stabilizer / equivalence relation  -- Stab(P) for a coloured pattern
  2. by generators and relations             -- a presentation
  3. in Chaim Goodman-Strauss's notation     -- the colour signature and type

Run with --check to verify the committed page is current.
"""

from __future__ import annotations

import argparse
import sys
from html import escape
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "torus-tutorial.html"

N = 3
CELLS = [(a, b) for a in range(N) for b in range(N)]

# Okabe-Ito, extended to nine entries for the free colouring.
PALETTE = ["#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9",
           "#D55E00", "#8C7BB0", "#B4A16B", "#6C7A89"]
LABELS = "ABCDEFGHI"


def span(generators: tuple[tuple[int, int], ...]) -> frozenset[tuple[int, int]]:
    seen = {(0, 0)}
    frontier = [(0, 0)]
    while frontier:
        x = frontier.pop()
        for g in generators:
            y = ((x[0] + g[0]) % N, (x[1] + g[1]) % N)
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    return frozenset(seen)


def cosets(subgroup: frozenset[tuple[int, int]]) -> dict[tuple[int, int], int]:
    """Cell -> coset index, with the coset of the origin numbered zero."""

    assigned: dict[tuple[int, int], int] = {}
    index = 0
    for cell in CELLS:
        if cell in assigned:
            continue
        for k in subgroup:
            assigned[((cell[0] + k[0]) % N, (cell[1] + k[1]) % N)] = index
        index += 1
    return assigned


def order_of(element: tuple[int, int]) -> int:
    steps, current = 1, element
    while current != (0, 0):
        current = ((current[0] + element[0]) % N, (current[1] + element[1]) % N)
        steps += 1
    return steps


