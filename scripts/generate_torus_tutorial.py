def build_records() -> list[dict[str, object]]:
    records = []
    for spec in SUBGROUPS:
        subgroup = span(tuple(spec["generators"]))          # type: ignore[arg-type]
        blocks = cosets(subgroup)
        colours = len(set(blocks.values()))
        rho_x = order_of((1, 0)) if (1, 0) not in subgroup else 1
        rho_y = order_of((0, 1)) if (0, 1) not in subgroup else 1
        records.append({
            **spec,
            "subgroup": subgroup,
            "blocks": blocks,
            "size": len(subgroup),
            "index": 9 // len(subgroup),
            "colours": colours,
            "short_signature": f"◦<sup>{rho_x},{rho_y}</sup>",
        })
    return records


def validate(records: list[dict[str, object]]) -> None:
    seen = set()
    for record in records:
        subgroup = record["subgroup"]
        assert isinstance(subgroup, frozenset)
        if subgroup in seen:
            raise ValueError(f"duplicate subgroup for {record['key']}")
        seen.add(subgroup)
        for x in subgroup:
            for y in subgroup:
                if ((x[0] + y[0]) % N, (x[1] + y[1]) % N) not in subgroup:
                    raise ValueError(f"{record['key']} is not closed")
        if record["colours"] != record["index"]:
            raise ValueError(f"{record['key']}: colours must equal the index")
        if 9 % len(subgroup):
            raise ValueError(f"{record['key']}: Lagrange violated")
    if len(seen) != 6:
        raise ValueError(f"expected 6 subgroups, found {len(seen)}")


